def rng(*key):
    return np.random.default_rng(zlib.crc32(repr(key).encode()))


def write_json(path, obj):
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump(obj, f, indent=2, ensure_ascii=False)
        f.write('\n')


