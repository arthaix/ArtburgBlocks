JOINTS = {'light': np.array((164, 160, 152), float), 'dark': np.array((58, 56, 54), float)}
CN = 96                     # clinker textures are 96 px (mipmaps need a multiple of 16): 1 px = 10.4 mm
BW = 6                      # a course is 6 px = 62.5 mm high (one Chisels & Bits bit), joint included
BL = 32                     # a brick is 32 px = 333 mm long: PIK's long facade clinker, about 300 x 60
# facade bonds: how far each course is shifted, in px, by course number
BONDS = {'running': lambda r: (r % 2) * (BL // 2),      # half bond
         'quarter': lambda r: (r % 4) * (BL // 4),      # quarter bond, a stepped diagonal
         'stack': lambda r: 0}                          # stack bond, head joints in line


def bricks(bond):
    """[(x0, y0, w, h)] on the CN px torus: horizontal courses, each brick once, checked to cover every texel once.
    On a wall every side face shows the texture upright, so the courses are level on all four sides."""
    out = [((k * BL + BONDS[bond](r)) % CN, r * BW, BL, BW) for r in range(CN // BW) for k in range(CN // BL)]
    cover = np.zeros((CN, CN), int)
    for (x0, y0, w, h) in out:
        cover[np.ix_(np.arange(y0, y0 + h) % CN, np.arange(x0, x0 + w) % CN)] += 1
    assert (cover == 1).all(), bond
    return out


def brick_texels(r, base, finish, effect, w, h):
    """The face of one brick, (h-1) x (w-1) texels, joints not included; NaN where an edge broke off.
    One flat colour per brick (the owner: no gradients inside a brick), only the fine grain of the material on it;
    the effects pick the colour of the whole brick."""
    sat = (base.max() - base.min()) / max(base.max(), 1)          # greys get almost no hue drift
    spread = 0.08 if finish != 'matte' else 0.06                  # glaze thickness varies more than fired clay
    c = base * (1 + r.normal(0, spread)) * (1 + r.normal(0, 0.004 + 0.03 * sat, 3))
    if effect == 'flamed' and r.random() < 0.45:                  # a brick that lay in the flame: darker all over
        c = c * r.uniform(0.45, 0.7)
    elif effect == 'smoked':
        c = c * r.uniform(0.5, 1.0)
    elif effect == 'whitewash':
        a = np.clip(0.4 + r.normal(0, 0.15), 0.1, 0.8)
        c = c * (1 - a) + np.array((228, 224, 214)) * a
    elif effect == 'antique':
        c = c * r.uniform(0.85, 1.0)
    hh, ww = h - 1, w - 1
    t = c * (1 + r.normal(0, 0.008 if finish != 'matte' else 0.012, (hh, ww, 1)))   # nearly one tone: a faint grain
    if finish == 'metal':
        t[r.random((hh, ww)) < 0.06] *= 1.08                      # faint metallic flecks
    if effect == 'antique':
        chip = np.zeros((hh, ww), bool)
        chip[0] |= r.random(ww) < 0.25
        chip[-1] |= r.random(ww) < 0.25
        chip[:, 0] |= r.random(hh) < 0.4
        chip[:, -1] |= r.random(hh) < 0.4
        t[chip] = np.nan                                          # the joint shows where an edge broke off
    return t


def clinker(bond, joint, palette, look, variant):
    sid = PALETTES[palette][3][look]
    jr = rng('joint', bond, joint, palette, look, variant)
    img = JOINTS[joint] * (1 + jr.normal(0, 0.04, (CN, CN, 1)))
    for n, (x0, y0, w, h) in enumerate(bricks(bond)):
        crosses = x0 + w > CN
        # a brick cut by the block edge must look the same in every variant, or it would change colour mid-brick
        r = rng('brick', bond, palette, look, n) if crosses else rng('brick', bond, palette, look, n, variant)
        one = sid
        if sid in MIXES:
            mix = MIXES[sid][2]
            p = np.array([m[1] for m in mix], float)
            one = mix[r.choice(len(mix), p=p / p.sum())][0]
        _, _, col, finish, effect = SHADES[one]
        t = brick_texels(r, np.array(col, float), finish, effect, w, h)
        ys = np.arange(y0, y0 + h - 1) % CN
        xs = np.arange(x0, x0 + w - 1) % CN
        face = img[np.ix_(ys, xs)]
        keep = ~np.isnan(t[..., 0])
        face[keep] = t[keep]
        img[np.ix_(ys, xs)] = face
        img[np.ix_([(y0 + h - 1) % CN], np.arange(x0, x0 + w) % CN)] *= 0.82   # the recessed bed joint lies in shadow
    return img


def clinker_family():
    kinds = [('running', 'light', 'Клинкер фасадный, ложковая перевязка', 'Facade Clinker, Running Bond'),
             ('running', 'dark', 'Клинкер фасадный, ложковая перевязка, тёмный шов', 'Facade Clinker, Running Bond, Dark Joint'),
             ('quarter', 'light', 'Клинкер фасадный, перевязка в четверть', 'Facade Clinker, Quarter Bond'),
             ('stack', 'light', 'Клинкер фасадный, стопкой', 'Facade Clinker, Stack Bond')]
    out = []
    for bond, joint, ru, en in kinds:
        for pi, (suffix, pru, pen, ids) in enumerate(PALETTES):
            looks = [(i, (SHADES.get(i) or MIXES[i])[0], (SHADES.get(i) or MIXES[i])[1]) for i in ids]
            name = 'clinker_' + bond + ('_dark' if joint == 'dark' else '') + suffix
            out.append({'name': name, 'material': 'rock', 'sound': 'stone', 'hardness': 1.5, 'map': 'red',
                        'ru': ru, 'en': en, 'looks': looks, 'variants': CLINKER_VARIANTS,
                        'paint': (lambda b, j, p: (lambda look, v: clinker(b, j, p, look, v)))(bond, joint, pi)})
    return out


