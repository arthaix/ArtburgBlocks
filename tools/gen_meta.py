def lang_section(blocks):
    ru, en = [LANG_MARK], [LANG_MARK]
    for b in blocks:
        for i, (lid, lru, len_) in enumerate(b['looks']):
            key = 'tile.artburgblocks.%s.%s.name' % (b['name'], lid)
            ru.append('%s=%s, %s' % (key, b['ru'], lru))
            en.append('%s=%s, %s' % (key, b['en'], len_))
    return ru, en


def put_lang(fname, lines):
    path = os.path.join(RES, 'lang', fname)
    text = open(path, encoding='utf-8').read()
    if LANG_MARK in text:
        text = text[:text.index(LANG_MARK)]
    text = text.rstrip('\n') + '\n' + '\n'.join(lines) + '\n'
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write(text)


def generate():
    blocks = [b for fam in FAMILIES for b in fam()]
    spec = []
    for b in blocks:
        name, looks = b['name'], b['looks']
        assert len(looks) <= 16, name
        variants = {}
        for i in range(16):
            li = i if i < len(looks) else 0
            if i < len(looks):
                for v in range(b.get('variants', VARIANTS)):
                    tex = '%s_%d_%d' % (name, i, v)
                    a = np.clip(np.round(b['paint'](i, v)), 0, 255).astype(np.uint8)
                    Image.fromarray(a, 'RGB').save(os.path.join(TEX, tex + '.png'))
                    write_json(os.path.join(RES, 'models', 'block', tex + '.json'),
                               {'parent': 'block/cube_all', 'textures': {'all': 'artburgblocks:blocks/' + tex}})
            variants['v=%d' % i] = [{'model': 'artburgblocks:%s_%d_%d' % (name, li, v)}
                                    for v in range(b.get('variants', VARIANTS))]
        write_json(os.path.join(RES, 'blockstates', name + '.json'), {'variants': variants})
        spec.append({k: b[k] for k in ('name', 'material', 'sound', 'hardness', 'map')} | {'looks': [l[0] for l in looks]})
        print('%-24s %2d looks' % (name, len(looks)))
    write_json(os.path.join(RES, 'meta_blocks.json'), spec)
    ru, en = lang_section(blocks)
    put_lang('ru_ru.lang', ru)
    put_lang('en_us.lang', en)
    return blocks


def preview(path, blocks):
    """A row per block: every look as 2x2 blocks with variants picked at random, labelled by index."""
    S, pad = 2, 10
    cell = 2 * CN * S
    cols = max(len(b['looks']) for b in blocks)
    canvas = Image.new('RGB', (cols * (cell + pad) + pad, len(blocks) * (cell + pad) + pad), (236, 236, 232))
    for row, b in enumerate(blocks):
        for i in range(len(b['looks'])):
            r = np.random.default_rng(row * 100 + i)
            tiles = [np.asarray(Image.open(os.path.join(TEX, '%s_%d_%d.png' % (b['name'], i, r.integers(b.get('variants', VARIANTS))))))
                     for _ in range(4)]
            n = tiles[0].shape[0]
            patch = np.zeros((2 * n, 2 * n, 3), np.uint8)
            for k, t in enumerate(tiles):
                patch[(k // 2) * n:(k // 2 + 1) * n, (k % 2) * n:(k % 2 + 1) * n] = t
            im = Image.fromarray(patch).resize((cell, cell), Image.NEAREST)
            canvas.paste(im, (pad + i * (cell + pad), pad + row * (cell + pad)))
    canvas.save(path)


