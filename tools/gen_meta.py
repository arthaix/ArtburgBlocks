def wall_brick(look, v):
    lid, _, _, col = WALL_BRICKS[look]
    n, L, H = 96, 24, 6
    jr = rng('wbj', look, v)
    joint = (150, 146, 138) if not lid.endswith('sooty') else (100, 96, 92)
    img = np.array(joint, float) * (1 + jr.normal(0, 0.04, (n, n, 1)))
    for row in range(n // H):
        off = (row % 2) * (L // 2)
        for k in range(n // L):
            x0 = (k * L + off) % n
            crosses = x0 + L > n
